std::vector< std::uint64_t > AStar_di_unipi_it::random_table(
 std::size_t n , std::uint64_t seed )
{
 std::mt19937_64 gen( seed );
 std::vector< std::uint64_t > r( n );
 for( auto & x : r )
  x = gen();
 return( r );
 }

